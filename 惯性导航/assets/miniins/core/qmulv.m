function vn = qmulv(q, vb)
% qmulv - 用四元数旋转向量：vn = Cbn·vb（比力方程用，省去构造矩阵）
%
% ─── 公式 2.13 ─────────────────────────────────────────────────────
%   q     姿态四元数（体→导航，归一化）  4×1
%   vb    体坐标系向量                  3×1
%   vn    = Cbn·vb  导航系向量          3×1
%
%   [0; vn] = q ⊗ [0; vb] ⊗ q*    （把 vb 补成纯四元数再双乘）
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 本质 = 姿态阵乘法 Cbn·vb，但用四元数实现省去构造矩阵（快）；
%   · 读法：先左乘 q（转到"中间系"）、再右乘 q*（转回来），
%     等价于"把向量按 q 转一次"；
%   · 自检：qmulv(q, vb) == q2cnb(q)*vb（数值一致）。
%
%   自行跑代码：验证x 轴单位向量绕 z 转 90°，变成了 y 轴单位向量
%     q = [cos(pi/4); 0; 0; sin(pi/4)];
%     v = [1; 0; 0];
%     v_rot = qmulv(q, v)  % 应为 [0; 1; 0]


% ─── 代码（公式 2.13）───────────────────────────────────────────────
q = q / norm(q);                             % 归一化（四元数旋转要求单位模长） （！必须！∵浮点误差会让模长漂移）
vq = [0; vb];                                % 补成纯四元数（实部 0，公式 2.13）
vn = qmul(qmul(q, vq), qconj(q)); % q ⊗ v ⊗ q*（公式 2.13）
vn = vn(2:4);                                % 丢掉实部，取向量部分
end
