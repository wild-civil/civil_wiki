function q = cnb2q(Cbn)
% cnb2q - 姿态阵 → 四元数 q（q2cnb 的逆，用于从 Cbn 提取四元数）
%
% ─── 公式 2.4（符号表）─────────────────────────────────────────────
%   Cbn   姿态阵（体→导航）                      3×3
%   q     = [w; x; y; z] 姿态四元数（标量在前）  4×1
%
%   提取法（trace 法，要求 Cbn 是合法旋转阵）：
%     w = 0.5·sqrt(1 + tr(Cbn))
%     x = (Cbn(3,2) - Cbn(2,3)) / (4w)
%     y = (Cbn(1,3) - Cbn(3,1)) / (4w)
%     z = (Cbn(2,1) - Cbn(1,2)) / (4w)
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 思路：旋转阵的"迹"（对角线之和）与旋转角 θ 满足 tr(C)=1+2cosθ，
%     由 cosθ 得 w（=cos(θ/2)）；叉乘项 C(3,2)-C(2,3) = 4w·x 给出 x，
%     其余类推——所以本质是"从迹和反对称部分反解四元数"。
%   · 若 Cbn 含数值噪声（非法旋转阵），w 可能 >1 或 <0：工程上先
%     clip(w, 0, 1) 再开方，并做符号归一（保证 w>0，与 PSINS 约定一致）。
%   · 自检：cnb2q(q2cnb(q)) 应 ≈ q（数值误差 ~1e-16）。

% ─── 代码（公式 2.4 逐行）───────────────────────────────────────────
tr = trace(Cbn);                          % 旋转阵迹 tr = 1+2cosθ（公式 2.4 用）
w  = 0.5 * sqrt(max(1 + tr, 0));          % w = cos(θ/2)；clip 防数值噪声
if w < 1e-12                              % 极端情况 θ≈180° 时 w≈0，4w 会除零
    error('cnb2q: 旋转角接近 180°，trace 法失效（本库未实现 Shepperd 法）');
end
x = (Cbn(3,2) - Cbn(2,3)) / (4*w);        % x = (C(3,2)-C(2,3))/(4w)（公式 2.4）
y = (Cbn(1,3) - Cbn(3,1)) / (4*w);        % y
z = (Cbn(2,1) - Cbn(1,2)) / (4*w);        % z
q = [w; x; y; z];                         % 拼成四元数
if q(1) < 0, q = -q; end                  % 符号归一：强制 w>0（PSINS a2qua 同款约定）
end
