function q = rv2q(rv)
% rv2q - 旋转矢量 → 四元数（姿态更新的"体轴增量→四元数"）
%
% ─── 公式 2.15 ─────────────────────────────────────────────────────
%   rv  旋转矢量（转角 θ、转轴 e）  3×1
%   q   = [cos(θ/2); sin(θ/2)·e]   4×1
%   其中 θ = |rv|，e = rv/θ
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 四元数"半角"本质就在这：转角 θ 进了四元数要除 2（所以
%     绕 z 转 90° 的四元数是 [cos45°;0;0;sin45°]，不是 [cos90°;...]）；
%   · 与 rv2m 同源（旋转矢量的两种"指数映射"），用哪个取决于下游
%     要矩阵还是四元数——insupdate 姿态更新用四元数版（左乘右乘
%     都方便）；
%   · 自检：rv2q(rv) == cnb2q(rv2m(rv))（两种路径一致）。

% ─── 代码（公式 2.15 逐行）──────────────────────────────────────────
theta = norm(rv);                    % 转角 θ = |rv|
if theta < 1e-10                     % 小角极限：sin(θ/2)≈θ/2, cos(θ/2)≈1
    q = [1; rv/2];                   % 一阶近似（避免除零）
else
    q = [cos(theta/2); sin(theta/2) * rv/theta];  % 公式 2.15：e = rv/θ
end
q = q / norm(q);                     % 归一化（四元数旋转要求单位模长）
end
