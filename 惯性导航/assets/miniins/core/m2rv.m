function rv = m2rv(C)
% m2rv - 旋转矩阵 → 旋转矢量（rv2m 的逆，姿态增量提取）
%
% ─── 公式 2.12（符号表）────────────────────────────────────────────
%   C   旋转矩阵                      3×3
%   rv  旋转矢量（转角 θ、转轴 e）    3×1
%
%   θ = acos( (tr(C) − 1) / 2 )
%   rv = θ / (2·sinθ) · vecc(C − C')      （θ 较大时）
%   rv = vecc(C − C') / 2                 （θ→0 小角近似）
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 用途：P2 讲过的"姿态增量提取"——由相邻两拍姿态阵之差
%     Cbn_1*Cnb 直接得旋转矢量（PSINS insupdate 姿态更新就这么干），
%     比四元数符号判断稳（[P2 坑 1](P2_纯惯导_拆解test_SINS.md)）；
%   · 旋转阵的迹 tr(C)=1+2cosθ，所以 θ 从迹反解；反对称部分
%     (C−C')/2 = sinθ·[e×] 给出转轴方向 e；
%   · 自检：m2rv(rv2m(rv)) ≈ rv（θ 远离 π 时数值误差 ~1e-15）。

% ─── 代码（公式 2.12 逐行）──────────────────────────────────────────
cos_theta = (trace(C) - 1) / 2;                % cosθ = (tr(C)−1)/2（公式 2.12）
cos_theta = max(min(cos_theta, 1), -1);        % clip 防数值越界（acos 定义域 [-1,1]）
theta = acos(cos_theta);                       % θ
D = C - C';                                    % 反对称部分（转置差）
if theta < 1e-10                               % 小角：sinθ≈θ → 系数 θ/(2sinθ)→1/2
    rv = vecc(D) / 2;                      % rv = vecc(C−C')/2（公式 2.12 小角行）
else
    rv = vecc(D) * theta / (2*sin(theta)); % rv = θ/(2sinθ)·vecc(C−C')（一般行）
end
end
