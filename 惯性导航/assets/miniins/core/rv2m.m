function C = rv2m(rv)
% rv2m - 旋转矢量 → 旋转矩阵（Rodrigues 公式，Mini-INS 基础转换系列）
%
% ─── 公式 2.11（符号表）────────────────────────────────────────────
%   rv  旋转矢量 = 旋转角 θ × 转轴单位向量 e（θ=|rv|）  3×1
%   C   旋转矩阵                                       3×3
%
%   C = I + (sinθ/θ)·[rv×] + ((1−cosθ)/θ²)·[rv×]²
%   其中 [rv×] = skew(rv)。小角时 sinθ/θ→1、(1−cosθ)/θ²→1/2。
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 旋转矢量是姿态的"指数坐标"：方向 = 转轴，长度 = 转角。
%     惯导里姿态更新算出的 φm 就是旋转矢量，用它一步到位地构造
%     旋转矩阵/四元数（不用分三步欧拉角）；
%   · **为什么不直接欧拉角**：旋转矢量无顺序歧义、无万向节死锁，
%     且天然适配"增量"语义（双子样圆锥补偿的结果就是旋转矢量）；
%   · 自检：rv=[0;0;pi/2]（绕 z 转 90°）→ C=[0 -1 0;1 0 0;0 0 1]。

% ─── 代码（公式 2.11 逐行）──────────────────────────────────────────
theta = norm(rv);                    % 旋转角 θ = |rv|（公式 2.11 的 θ）
S = skew(rv);                    % [rv×] 反对称阵（公式 2.11 的 [rv×]）
if theta < 1e-10                     % 小角极限：sinθ/θ→1, (1−cosθ)/θ²→1/2
    C = eye(3) + S + 0.5*S*S;        % 二阶泰勒（比 C=I+S 更准，仍避除零）
else
    C = eye(3) + (sin(theta)/theta)*S + ((1-cos(theta))/theta^2)*S*S;  % 公式 2.11
end
end
