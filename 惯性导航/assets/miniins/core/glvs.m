function glv = glvs()
% glvs - 地球模型与单位常量（对标 PSINS glvs.m，零依赖自写）
%
% 新手速览：
%   - glv 是 Mini-INS 的"全局量"结构体，装着一辈子都用得上的常量；
%   - 对标 PSINS 的 global glv，但本库不强制 global——你可以在函数里
%     显式传参，或在工作区先 glv = glvs() 再用；
%   - 所有单位换算常量（deg/min/deg2rad 等）都放这里，别在代码里写裸数字。
%
% 公式层：本文件只是常量表，无公式。对应 wiki 第 0 篇约定 1（global glv）与约定 5（rad 单位）。
%
% 输出:
%   glv - 结构体，字段见下

%% 地球基本参数（WGS-84）
glv.Re = 6378137.0;              % 地球长半轴 (m)          —— 赤道半径，纬向曲率半径 RM 的分母底子
glv.f  = 1/298.257223563;        % 扁率 (无单位)            —— 地球不是正球，扁率决定子午圈/卯酉圈半径差
glv.e  = sqrt(2*glv.f - glv.f^2);% 第一偏心率 (无单位)       —— 由扁率推出，用于计算曲率半径

%% 运动学常量
glv.wie = 7.2921151467e-5;       % 地球自转角速度 (rad/s)    —— 惯性导航必须补偿的"惯性参考旋转"
glv.g0  = 9.7803267714;          % 赤道标准重力 (m/s^2)     —— 比力方程里的 g（更精确的随纬度/高度变化见 earth.m）

%% 单位换算（PSINS 风格：角度全程弧度，别写裸的 3.14159）
glv.deg = pi/180;                % 度  → 弧度：angle_rad = angle_deg * glv.deg
glv.min = glv.deg/60;            % 分  → 弧度：1 度 = 60 分
glv.sec = glv.min/60;            % 秒  → 弧度：1 分 = 60 秒
glv.dph = glv.deg/3600;          % 度/小时 → 弧度/秒：陀螺零偏常用单位 °/h（1 °/h ≈ 4.85e-6 rad/s）
glv.ug  = 1e-6*glv.g0;           % 微 g → m/s^2：加计零偏常用单位 µg（1 µg ≈ 9.78e-6 m/s^2）

%% 其他常用
glv.wm_1 = [0 0 0]';             % 上一拍角增量（cnscl 圆锥补偿用，初始为 0）
glv.vm_1 = [0 0 0]';             % 上一拍速度增量（划桨补偿用，初始为 0）
end
