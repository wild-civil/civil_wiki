function kf = kfinit(n, ts)
% kfinit - 卡尔曼滤波器初始化（Mini-INS 组合导航 M4）
%
% 对标 PSINS `base/kf/kfinit.m`，本库教学简化版：返回标准 KF 结构，
% 具体噪声（P0/Qk/Rk/Hk）由调用方（demo）按场景配置——教学上把
% "滤波器骨架"和"场景参数"分开，读者先懂骨架，再看参数怎么填。
%
% ─── 输入 ─────────────────────────────────────────────────────────
%   n   状态维度（M4 用 22：INS15 + dposD3 + dinst2 + dKod1 + dT1）
%   ts  采样间隔（s）
%   kf  = KF 结构（字段见 data_classes('kf')，另加 ts）
%
% ─── 22 维状态布局（与 P4 一致）───────────────────────────────────
%   x = [ φ(3)  δv(3)  δr(3)  eb(3)  db(3) | dposD(3)  dinst(2)  dKod(1)  dT(1) ]
%        1:3    4:6    7:9    10:12  13:15   16:18      19:20     21       22
%        └────── SINS 15 维误差态 ──────┘  └──── DR 扩展 7 维 ────┘
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · KF 在这里只是"空壳"：Phikk_1（每步由 kffk 刷新）、Pk（初值）、
%     Qk/Rk/Hk（量测模型）都是场景相关的，demo_sins_dr 里统一配置；
%   · 为什么 22 维？15 维 SINS 误差态只够"修 SINS 自己"，要在线自标定
%     里程计（安装角 dinst、尺度 dKod、时延 dT）必须把 DR 的误差态也
%     并进状态向量——这就是"扩维"的意义（P4 第三节）。

kf = data_classes('kf', n);        % 标准 KF 结构（Phikk_1/Ft/Hk/Rk/Pk/xk/Qk/Gk）
kf.ts = ts;                        % 采样间隔（kffk 离散化用）
kf.Qk = zeros(n);                  % 过程噪声（demo 里按 IMU 精度/慢变参数填）
end
