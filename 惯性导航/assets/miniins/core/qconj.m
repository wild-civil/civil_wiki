function qc = qconj(q)
% qconj - 四元数共轭 q*（Mini-INS 基础转换系列）
%
% ─── 公式 2.8 ──────────────────────────────────────────────────────
%   q  = [w; x; y; z]    四元数       4×1
%   qc = [w; -x; -y; -z] 共轭        4×1
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 共轭 = "反向旋转"：q* ⊗ q = [1;0;0;0]（单位元）；
%     若 q 已归一化，则 q⁻¹ = q*（q 的逆就是共轭）——惯导里四元数
%     一般保持归一化，所以"反向旋转"直接写 qconj(q) 即可；
%   · **注意：共轭只翻虚部符号，绝不翻 w**（MATLAB 的 conj() 是复数
%     共轭，别混用——[P2 坑 1](P2_纯惯导_拆解test_SINS.md) 就是栽在这）；
%   · 自检：qmul(q, qconj(q)) = [|q|²; 0; 0; 0]（归一化后 = 单位元）。

% ─── 代码（公式 2.8）────────────────────────────────────────────────
qc = [q(1); -q(2); -q(3); -q(4)];   % 只翻 x,y,z（虚部），w 不动
end
