function q = a2qua(att)
% a2qua - 姿态角 → 四元数（PSINS 约定，Mini-INS M4）
%
% 对标 PSINS `base/base0/a2qua.m`，逐元素一致。
%
% ─── 输入/输出 ─────────────────────────────────────────────────────
%   att = [pitch; roll; yaw]（弧度）  3×1
%   q   = [w; x; y; z]               4×1（单位四元数）
%
% ─── ⚠️ PSINS 机体系约定（M4 起全库统一，勿再用"航空 NED"直觉）───
%   · 机体系：**x 右、y 前、z 上**（不是航空的 x 前 y 右 z 下！）
%   · 姿态角对应轴：pitch 绕 x（右翼轴）、roll 绕 y（纵轴）、yaw 绕 z（竖轴）
%   · 后果（易踩坑）：
%     ① 体 y 轴 = 前进方向 → 里程计默认沿体 y（drinit 里 prj=Cbo·[0;1;0]）；
%     ② yaw=0 时车头朝北、yaw 增大 = 车头**左转**（北→西）；
%     ③ 与"标准航空 euler2cnb（pitch 绕 y）"差一个转置级（M4 已切换）。
%
% ─── 公式（逐元素对照 PSINS a2qua.m）──────────────────────────────
%   s = sin(att/2);  c = cos(att/2)
%   q = [c1c2c3 − s1s2s3;        % ⚠️ q0 是减号（曾写 +，导致 q2att 大角度不互逆）
%        s1c2c3 − c1s2s3;
%        c1s2c3 + s1c2s3;
%        c1c2s3 + s1s2c3]        % ⚠️ q3 是 "+s1s2c3"，与标准 ZYX 的 "−" 不同

s = sin(att/2);  c = cos(att/2);
q = [c(1)*c(2)*c(3) - s(1)*s(2)*s(3);
     s(1)*c(2)*c(3) - c(1)*s(2)*s(3);
     c(1)*s(2)*c(3) + s(1)*c(2)*s(3);
     c(1)*c(2)*s(3) + s(1)*s(2)*c(3)];
end
