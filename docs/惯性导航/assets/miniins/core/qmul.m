function q12 = qmul(q1, q2)
% qmul - 四元数乘法 q1 ⊗ q2（Mini-INS 基础转换系列）
%
% ─── 公式 2.7（符号表）─────────────────────────────────────────────
%   q1, q2  四元数 [w; x; y; z]（标量在前）  4×1
%   q12     = q1 ⊗ q2  合成旋转              4×1
%
%   | w1·w2 − x1·x2 − y1·y2 − z1·z2 |
%   | w1·x2 + x1·w2 + y1·z2 − z1·y2 |
%   | w1·y2 − x1·z2 + y1·w2 + z1·x2 |
%   | w1·z2 + x1·y2 − y1·x2 + z1·w2 |
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · **q1 ⊗ q2 = 先做 q2 的旋转、再做 q1 的旋转**（旋转合成顺序：
%     右边先转）。类比矩阵乘法 C = C1·C2 时 C2 先作用于向量。
%   · 四元数乘法不交换：q1⊗q2 ≠ q2⊗q1（和矩阵乘法同病）；
%   · 自检：q⊗q⁻¹ = [1;0;0;0]（单位四元数，q⁻¹ 见 qconj 后归一）。

% ─── 代码（公式 2.7 逐行）───────────────────────────────────────────
w1=q1(1); x1=q1(2); y1=q1(3); z1=q1(4);    % 展开 q1 分量
w2=q2(1); x2=q2(2); y2=q2(3); z2=q2(4);    % 展开 q2 分量
q12 = [w1*w2 - x1*x2 - y1*y2 - z1*z2;      % 第 1 行（公式 2.7）
       w1*x2 + x1*w2 + y1*z2 - z1*y2;      % 第 2 行
       w1*y2 - x1*z2 + y1*w2 + z1*x2;      % 第 3 行
       w1*z2 + x1*y2 - y1*x2 + z1*w2];     % 第 4 行
end
