function S = skew(v)
% skew - 叉乘的矩阵形式（反对称阵，Mini-INS 小工具）
%
% ─── 公式 2.9 ──────────────────────────────────────────────────────
%   v = [v1; v2; v3]    3×1
%   S = |  0  −v3   v2 |
%       | v3    0  −v1 |
%       |−v2   v1    0 |
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 用途：把叉乘 a×b 变成矩阵乘 S(a)·b——惯导公式（哥氏项、圆锥
%     补偿、旋转矢量）几乎全用矩阵形式书写，这是"从公式到代码"的
%     第一座桥；
%   · 自检：skew([1;2;3]) * [4;5;6] == [1;2;3] × [4;5;6] = [-3;6;-3]；
%   · 反对称阵性质：S' = −S（转置=取负），S·v = 0（自己叉自己=0）。

% ─── 代码（公式 2.9）────────────────────────────────────────────────
S = [0,    -v(3),  v(2);    % 第 1 行
     v(3),  0,    -v(1);    % 第 2 行
    -v(2),  v(1),  0];      % 第 3 行
end
