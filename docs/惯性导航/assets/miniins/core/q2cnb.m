function Cbn = q2cnb(q)
% q2cnb - 四元数 → 姿态阵 Cbn（体→导航），Mini-INS 基础转换系列
%
% ─── 公式 2.3（符号表）─────────────────────────────────────────────
%   q  = [w; x; y; z]  姿态四元数（标量 w 在前，体→导航）   4×1
%   Cbn               姿态阵（体坐标系 → 导航坐标系的旋转阵） 3×3
%
%   Cbn = | 1-2(y²+z²)   2(xy-zw)      2(xz+yw)   |
%         | 2(xy+zw)     1-2(x²+z²)    2(yz-xw)   |
%         | 2(xz-yw)     2(yz+xw)      1-2(x²+y²) |
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 矩阵第 1 行只含 y、z 和交叉项，第 2 行只含 x、z——记不住没关系，
%     这是纯机械代换，**你只需要会查表**；
%   · 真正要理解的是 Cbn 的物理含义：**第 1 列 = 体 x 轴在导航系的投影
%     （方向余弦）**，第 2/3 列同理。Cbn 把体坐标向量转到导航系：
%     vn = Cbn * vb。
%   · 自检：q = [1;0;0;0]（零旋转）→ 单位阵；q = [cos45°;0;0;sin45°]
%     （绕 z 转 90°）→ Cbn = [0 -1 0; 1 0 0; 0 0 1]。

% ─── 代码（一行对一行，w=q(1), x=q(2), y=q(3), z=q(4)）─────────────
w = q(1); x = q(2); y = q(3); z = q(4);        % 展开四元数分量（公式 2.3 的 w,x,y,z）
Cbn = [1-2*(y^2+z^2),  2*(x*y - z*w),  2*(x*z + y*w);   % 第 1 行（公式 2.3 第 1 行）
       2*(x*y + z*w),  1-2*(x^2+z^2),  2*(y*z - x*w);   % 第 2 行
       2*(x*z - y*w),  2*(y*z + x*w),  1-2*(x^2+y^2)];  % 第 3 行
end
