function v = vecc(S)
% vecc - 反对称阵 → 向量（skew 的逆，提取叉乘向量）
%
% ─── 公式 2.10 ─────────────────────────────────────────────────────
%   S = |  0  −v3   v2 |           v = | S(3,2) |
%       | v3    0  −v1 |    ==>       | S(1,3) |
%       |−v2   v1    0 |             | S(2,1) |
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · m2rv（旋转阵→旋转矢量）的核心一步：旋转阵的反对称部分
%     (C − C')/2 里藏着旋转轴方向，vecc 把它提出来；
%   · 自检：vecc(skew([1;2;3])) = [1;2;3]（skew 与 vecc 互逆）。

% ─── 代码（公式 2.10）───────────────────────────────────────────────
v = [S(3,2); S(1,3); S(2,1)];   % 反对称阵的"对角对"元素 → 向量分量
end
