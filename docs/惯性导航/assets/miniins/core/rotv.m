function vn = rotv(rv, v)
% rotv - 用旋转矢量旋转向量：vn = C(rv)·v（速度更新/补偿用）
%
% ─── 公式 2.14 ─────────────────────────────────────────────────────
%   rv  旋转矢量（转角 × 轴）  3×1
%   v   待旋转向量            3×1
%   vn  = rv2m(rv)·v          旋转后的向量  3×1
%
% ─── 新手备注 ───────────────────────────────────────────────────────
%   · 速度更新里的典型用法：比力 fn 要先"反向旋转半拍"（补偿导航系
%     在这半拍内的旋转 −wnin·nts/2），用的就是 rotv(−wnin·nts/2, fn)；
%   · 实现直接用 rv2m（教学版，清晰优先）；PSINS 的 rotv 有避免构造
%     矩阵的快速算法，原理相同；
%   · 自检：rotv([0;0;pi/2], [1;0;0]) = [0;1;0]（绕 z 转 90°，x→y）。

% ─── 代码（公式 2.14）───────────────────────────────────────────────
vn = rv2m(rv) * v;   % 旋转矢量→矩阵→乘向量（公式 2.14）
end
